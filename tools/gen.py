#!/usr/bin/env python3
"""Certificates for every machine with 1 or 2 states, as Lean (`lean/Bbbb/Certs*.lean`).

The window simulation, `crit` and the codes follow `Window.lean`, `Decider.lean` and
`Codes.lean` exactly.  Usage: tools/gen.py  (writes the Lean files, prints a summary).
"""
import itertools, os, sys

ANY, BLANK = 'any', 'blank'


def dec_tr(n, c):
    if c == 0:
        return None
    x = c - 1
    return (x // (2 * (n + 1)) == 1, 'R' if (x // (n + 1)) % 2 == 0 else 'L', x % (n + 1))


def machine(n, codes):
    # codes in the order (state 0 reading 0, state 0 reading 1, state 1 reading 0, ...)
    return {(q, s): dec_tr(n, codes[2 * q + s]) for q in range(n + 1) for s in (0, 1)}


def head_r(kr, r):
    if r:
        return r[0]
    return False if kr == BLANK else None


def wstep(M, kl, kr, w):
    q, l, r = w
    b = head_r(kr, r)
    if b is None:
        return 'stuck'
    t = M[(q, int(b))]
    if t is None:
        return 'halt'
    x, d, q2 = t
    if d == 'R':
        return (q2, [x] + l, r[1:])
    if l:
        return (q2, l[1:], [l[0], x] + r[1:])
    if kl == BLANK:
        return (q2, [], [False, x] + r[1:])
    return 'stuck'


def wrun(M, kl, kr, n, w):
    ls = []
    for _ in range(n):
        b = head_r(kr, w[2])
        s = wstep(M, kl, kr, w)
        if b is None or not isinstance(s, tuple):
            return None
        ls.append((w[0], b))
        w = s
    return w, ls


def strip(l):
    l = list(l)
    while l and not l[-1]:
        l.pop()
    return l


def is_pre(l, m):
    return m[:len(l)] == l


def ret(k, l, l2):
    return is_pre(l, l2) if k == ANY else strip(l) == strip(l2)


def fit(k, l, lc):
    return is_pre(l, lc + [False] * len(l)) if k == ANY else strip(l) == strip(lc)


def seqv(pre, per, n):
    return pre[n] if n < len(pre) else per[(n - len(pre)) % len(per)]


def crit(pre, per, K):
    t0 = len(pre)
    for d in range(len(per)):
        if not t0 + d < K:
            return False
        if not any(e != d and seqv(pre, per, t0 + e) == seqv(pre, per, t0 + d)
                   for e in range(K - t0)):
            return False
    return True


WINIT = (0, [], [])


def find_cert(M, K, T=16, P=16, W=4):
    for t in range(T + 1):
        r = wrun(M, BLANK, BLANK, t, WINIT)
        if r is None:
            return None
        wc, _ = r
        if wstep(M, BLANK, BLANK, wc) == 'halt':
            return ('halt', t)
    for t0 in range(T + 1):
        wc, ls0 = wrun(M, BLANK, BLANK, t0, WINIT)
        for kl in (BLANK, ANY):
            for kr in (BLANK, ANY):
                lsizes = range(W + 1) if kl == ANY else [None]
                rsizes = range(W + 1) if kr == ANY else [None]
                for nl in lsizes:
                    for nr in rsizes:
                        l = list(wc[1]) if nl is None else (wc[1] + [False] * nl)[:nl]
                        r = list(wc[2]) if nr is None else (wc[2] + [False] * nr)[:nr]
                        assert fit(kl, l, wc[1]) and fit(kr, r, wc[2])
                        for p in range(1, P + 1):
                            x = wrun(M, kl, kr, p, (wc[0], l, r))
                            if x is None:
                                break
                            w1, ls = x
                            if (w1[0] == wc[0] and ret(kl, l, w1[1]) and ret(kr, r, w1[2])
                                    and crit(ls0, ls, K)):
                                return ('per', t0, p, l, r, kl, kr)
    return None


def lean_bools(l):
    return '[' + ', '.join('true' if b else 'false' for b in l) + ']'


def lean_cert(c):
    if c is None:
        return '.holdout'
    if c[0] == 'halt':
        return f'.halt {c[1]}'
    _, t0, p, l, r, kl, kr = c
    return f'.per {t0} {p} {lean_bools(l)} {lean_bools(r)} .{kl} .{kr}'


def name(n, codes):
    def tt(x):
        if x is None:
            return '---'
        w, d, q = x
        return f"{int(w)}{d}{'AB'[q]}"
    M = machine(n, codes)
    return '_'.join(''.join(tt(M[(q, s)]) for s in (0, 1)) for q in range(n + 1))


HEADER = '''import Bbbb.Codes

/-! Generated by `tools/gen.py`: a certificate for every {k}-state machine. -/

namespace Bbbb

'''


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lean', 'Bbbb')
    # 1 state, K = 2
    out = []
    hold1 = []
    for a in range(5):
        for b in range(5):
            c = find_cert(machine(0, (a, b)), 2)
            if c is None:
                hold1.append((a, b))
            out.append(lean_cert(c))
    print('1 state: holdouts', hold1)
    with open(os.path.join(root, 'Certs1.lean'), 'w') as f:
        f.write(HEADER.format(k=1))
        f.write('/-- the certificate of `ofCodes1 a b` is entry `5 a + b` -/\n')
        f.write('def certs1 : List Cert := [\n  ' + ',\n  '.join(out) + ']\n\nend Bbbb\n')
    # 2 states, K = 18
    chunks = []
    hold2 = []
    stats = {'halt': 0, 'per': 0}
    for a in range(9):
        for b in range(9):
            ch = []
            for c_ in range(9):
                for d in range(9):
                    codes = (a, b, c_, d)
                    c = find_cert(machine(1, codes), 18)
                    if c is None:
                        hold2.append(codes)
                    else:
                        stats[c[0]] += 1
                    ch.append(lean_cert(c))
            chunks.append(ch)
    print('2 states:', stats, 'holdouts', len(hold2))
    for h in hold2:
        print('  ', h, name(1, h))
    with open(os.path.join(root, 'Certs2.lean'), 'w') as f:
        f.write(HEADER.format(k=2))
        for k, ch in enumerate(chunks):
            f.write(f'/-- certificates of `ofCodes2 {k // 9} {k % 9} c d`, entry `9 c + d` -/\n')
            f.write(f'def certs2_{k} : List Cert := [\n  ' + ',\n  '.join(ch) + ']\n\n')
        f.write('/-- the 2-state machines without a certificate -/\n')
        f.write('def holdouts2 : List (Nat × Nat × Nat × Nat) := [\n  ' +
                ',\n  '.join(f'({a}, {b}, {c}, {d})' for a, b, c, d in hold2) + ']\n\n')
        f.write('end Bbbb\n')
    with open(os.path.join(root, 'Enum2.lean'), 'w') as f:
        f.write('''import Bbbb.Chunk

/-! Generated by `tools/gen.py`: the kernel checks every certificate of a 2-state machine. -/

namespace Bbbb

''')
        for k in range(81):
            f.write(f'theorem chunk2_{k} : chunkOK2 {k // 9} {k % 9} certs2_{k} = true := by decide\n')
        f.write('''
theorem exists_chunk2 (a b : Nat) (ha : a < 9) (hb : b < 9) : ∃ cs, chunkOK2 a b cs = true := by
  match a, ha with
''')
        for a in range(9):
            f.write(f'  | {a}, _ =>\n    match b, hb with\n')
            for b in range(9):
                f.write(f'    | {b}, _ => exact ⟨_, chunk2_{9 * a + b}⟩\n')
            f.write('    | _ + 9, hb => exact absurd hb (by omega)\n')
        f.write('  | _ + 9, ha => exact absurd ha (by omega)\n\nend Bbbb\n')


if __name__ == '__main__':
    main()
